async function main() {
  console.log('--- 1. Updating buyers with realistic company names ---');
  for (const buyer of BUYER_UPDATES) {
    try {
      await prisma.user.update({
        where: { id: buyer.id },
        data: {
          fullName: buyer.fullName,
          companyName: buyer.companyName,
        },
      });
      console.log(`Updated buyer: ${buyer.fullName}`);
    } catch (err) {
      console.warn(`Could not update buyer ${buyer.id}:`, err.message);
    }
  }

  console.log('\n--- 2. Fetching categories map ---');
  const categories = await prisma.category.findMany({ select: { id: true, slug: true } });
  const catMap = {};
  for (const c of categories) {
    catMap[c.slug] = c.id;
  }
  console.log('Categories found:', Object.keys(catMap));

  console.log('\n--- 3. Clearing old jobs ---');
  const deleted = await prisma.job.deleteMany({});
  console.log(`Deleted ${deleted.count} existing jobs.`);

  console.log('\n--- 4. Inserting 100 authentic online jobs ---');
  const now = new Date();
  let inserted = 0;

  for (let i = 0; i < RAW_JOBS.length; i++) {
    const item = RAW_JOBS[i];
    const categoryId = catMap[item.category];
    if (!categoryId) {
      console.error(`Unknown category: ${item.category}`);
      continue;
    }
    const buyer = BUYER_UPDATES[item.buyerIdx % BUYER_UPDATES.length];

    const createdAt = new Date(now.getTime() - item.daysAgo * 86400000 - (i % 24) * 3600000);
    const deadline = new Date(now.getTime() + item.deadlineDays * 86400000);

    // Budget in tiyin (so'm * 100n)
    const budgetMinTiyin = BigInt(item.budgetMin) * 100n;
    const budgetMaxTiyin = BigInt(item.budgetMax) * 100n;

    const id = crypto.randomUUID();

    await prisma.job.create({
      data: {
        id,
        buyerId: buyer.id,
        categoryId,
        title: item.title,
        description: item.description,
        budgetMin: budgetMinTiyin,
        budgetMax: budgetMaxTiyin,
        currency: 'UZS',
        skillsRequired: item.skills,
        screeningQuestions: item.questions || [],
        proposalsCount: 0,
        status: 'OPEN',
        deadline,
        attachedImages: [],
        createdAt,
        updatedAt: createdAt,
        version: 0,
      },
    });
    inserted++;
  }

  console.log(`\n=== Successfully inserted ${inserted} jobs into the database! ===`);

  // Verify count
  const count = await prisma.job.count({ where: { status: 'OPEN' } });
  console.log(`Total OPEN jobs in DB: ${count}`);
}

main()
  .catch((e) => {
    console.error('Seed error:', e);
    process.exit(1);
  })
  .finally(async () => {
    await prisma.$disconnect();
  });
